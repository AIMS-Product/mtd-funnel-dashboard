#!/usr/bin/env python3
"""V2 funnel/team CSVs and month comparisons from aggregate-only report data."""

from __future__ import annotations

import argparse
import csv
import importlib
import json
import sys
import tempfile
from datetime import date, datetime, time, timedelta
from pathlib import Path

from aggregates import APPOINTMENT_BOOKING_SCOPE, CLOSERS, METRICS, OTHER_OWNER, booking_scope_label
from reporting import ARCHIVE_START, PACIFIC, ROOT

HEADERS = ["Funnel", "Leads", "Booked", "Projected", "Goal %", "Showed", "Show %", "Qualified", "Qual %", "Closed", "CW %", "Revenue", "Rev / Close"]


def rate(a, b):
    return f"{100 * a / b:.1f}%" if b else "—"


def money(value):
    return f"${value:,.0f}"


def funnel_rows(data):
    include_occurred = 'occurred_calls' in data['totals']
    headers = list(HEADERS)
    if include_occurred: headers.insert(5, 'Calls Occurred')
    rows = [headers]
    for row in [*data["channels"], {"channel": "TOTAL", **data["totals"]}]:
        display = row.get("display", {})
        goal = display.get("goal")
        cells = [
            row["channel"], row.get("leads_created", 0), row["bookings"],
            display.get("projected") if display.get("projected") is not None else "—",
            f"{display['goal_pct']}% ({goal:,})" if goal else "—",
            row["showed"], rate(row["showed"], row.get("occurred_calls", row["bookings"])),
            row["qualified"], rate(row["qualified"], row.get("occurred_calls", row["showed"])),
            row["closed_won"], rate(row["closed_won"], row.get("occurred_calls", row["bookings"])),
            money(row["revenue"]), money(row["revenue"] / row["closed_won"]) if row["closed_won"] else "—",
        ]
        if include_occurred: cells.insert(5, row.get('occurred_calls', 0))
        rows.append(cells)
    return rows


def pipeline_snapshot(reader, now):
    """Reuse only the legacy point-in-time pipeline helper, never its booking fetch."""
    sys.path.insert(0, str(ROOT.parent))
    legacy = importlib.import_module("generate_team_report")
    if tuple(legacy.CLOSERS) != CLOSERS:
        raise ValueError("V2 and current team-report closer rosters must agree")
    original = legacy.close_get
    try:
        legacy.close_get = reader.get
        counts, _ = legacy.fetch_open_qualified_by_closer(now)
    finally:
        legacy.close_get = original
    return {"generated_at": now.isoformat(), "counts": counts,
            "basis": "Current open qualified leads owned within trailing 30 days; $7,000 × 20% per lead. Independent of report week."}


def team_rows(data):
    include_occurred = 'occurred_calls' in data['totals']
    rows = [["## REPORT METADATA"], ["Report", "V2 Team Performance"],
            ["Period", data["period"]], ["Generated At", data["generated_at"]],
            ["Booking Rules", data["rules_version"]],
            ["Booking Scope", booking_scope_label(data.get("booking_scope"))],
            ["Attribution", "Booking/show by appointment closer; distinct qualification credit by canonical meeting; won deals/revenue by opportunity owner." if data.get('booking_scope') == APPOINTMENT_BOOKING_SCOPE else "Booking/show/qualified by current Lead Owner; won deals/revenue by opportunity owner."],
            ["Qualification", "Distinct qualified source/lead cohort, allocated once to the canonical meeting's closer." if data.get('booking_scope') == APPOINTMENT_BOOKING_SCOPE else "Distinct currently qualified leads among occurred calls per owner." if include_occurred else "Distinct qualified booked leads per owner, using the same V2 credits."], []]
    reps = {row["value"]: row for row in data.get("team", [])}
    metric_fields = (*METRICS, 'occurred_calls') if 'occurred_calls' in data['totals'] else METRICS
    empty = dict.fromkeys(metric_fields, 0)
    closer_total = {key: sum(reps.get(name, empty)[key] for name in CLOSERS) for key in metric_fields}
    pipeline = data.get("pipeline", {})
    counts = pipeline.get("counts", {})
    rev_goal = closer_total["bookings"] * .13 * 7000
    rows += [["## TEAM KPI TILES"], ["Metric", "Actual", "Goal"],
             ["Closer Revenue", money(closer_total["revenue"]), money(rev_goal)],
             ["Closer Show Rate", rate(closer_total["showed"], closer_total.get("occurred_calls", closer_total["bookings"])), "65.0%"],
             ["Closer Close Rate / Occurred" if "occurred_calls" in data["totals"] else "Closer Close Rate / Booked", rate(closer_total["closed_won"], closer_total.get("occurred_calls", closer_total["bookings"])), "13.0%"],
             ["Closer Close Rate / Qualified", rate(closer_total["closed_won"], closer_total["qualified"]), "20.0%"],
             ["Pipeline", money(sum(counts.values()) * 1400) if counts else "Not captured", "$840,000"],
             ["Pipeline snapshot", pipeline.get("generated_at", "Not captured")],
             ["Pipeline basis", pipeline.get("basis", "Generated by the V2 report workflow")], [],
             ["## REP BREAKDOWN"],
             ["Rep", "Booked", "Showed", "Show %", "Qualified", "Qual %", "Closed Won", "CW %", "Qualified to Close %", "Revenue", "Avg Deal", "Revenue Goal", "Pipeline", "Open Qualified"]]
    if include_occurred: rows[-1].insert(2, 'Calls Occurred')
    for name, row in [(name, reps.get(name, empty)) for name in CLOSERS] + [(OTHER_OWNER, reps.get(OTHER_OWNER, empty)), ("CLOSERS TOTAL", closer_total), ("ALL V2 TOTAL", data["totals"])]:
        count = sum(counts.values()) if name == "CLOSERS TOTAL" else counts.get(name)
        rows.append([name, row["bookings"], row["showed"], rate(row["showed"], row.get("occurred_calls", row["bookings"])),
                     row["qualified"], rate(row["qualified"], row.get("occurred_calls", row["showed"])), row["closed_won"],
                     rate(row["closed_won"], row.get("occurred_calls", row["bookings"])), rate(row["closed_won"], row["qualified"]),
                     money(row["revenue"]), money(row["revenue"] / row["closed_won"]) if row["closed_won"] else "—",
                     money(row["bookings"] * .13 * 7000), money(count * 1400) if count is not None else "—", count if count is not None else "—"])
        if include_occurred: rows[-1].insert(2, row.get('occurred_calls', 0))
    rows += [[], ["## RECONCILIATION"], ["Metric", "Rep sum including Other", "V2 funnel total", "Match"]]
    for key in (("bookings", "occurred_calls", "showed", "qualified", "closed_won", "revenue") if include_occurred else ("bookings", "showed", "qualified", "closed_won", "revenue")):
        total = sum(row[key] for row in reps.values())
        if abs(total - data["totals"][key]) > .01:
            raise ValueError(f"V2 team reconciliation mismatch: {key}")
        rows.append([key, total, data["totals"][key], "YES"])
    return rows


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as stream:
        csv.writer(stream).writerows(rows)


def write_exports(data, directory, key):
    write_csv(directory / f"funnel-{key}.csv", funnel_rows(data))
    if data.get("team") or not any(data["totals"][key] for key in ("bookings", "showed", "qualified", "closed_won", "revenue")):
        write_csv(directory / f"team-{key}.csv", team_rows(data))
    if data.get('setters'):
        write_csv(directory / f"setters-{key}.csv", [['Setter', *METRICS]] + [[row['value'], *[row[field] for field in METRICS]] for row in data['setters']])


def write_comparison(reports, path):
    from archive_ui import write_current_comparison
    write_current_comparison(reports, path)


def main():
    from build import CloseReader, build_dataset, load_api_key
    from publish_shadow import public_data
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--start", required=True)
    parser.add_argument("--end", required=True)
    args = parser.parse_args()
    start, end = date.fromisoformat(args.start), date.fromisoformat(args.end)
    now = datetime.now(PACIFIC)
    if start < ARCHIVE_START or end < start or end > now.date():
        parser.error("Use an October 2026-or-later reporting window ending no later than today")
    reader = CloseReader(load_api_key())
    cutoff = min(now, datetime.combine(end + timedelta(days=1), time.min, PACIFIC))
    raw = build_dataset(reader, cutoff, start)
    raw["generated_at"] = now.isoformat()
    with tempfile.TemporaryDirectory(prefix="mtd-v2-private-") as directory:
        source = Path(directory) / "data.json"
        source.write_text(json.dumps(raw))
        data = public_data(source)
    from outcome_core import ReportingReader, scheduled_dataset, occurred_dataset
    from outcome_public import apply_occurred_mtd
    outcome_reader = ReportingReader(reader.get, start, cutoff)
    scheduled = scheduled_dataset(outcome_reader)
    data = apply_occurred_mtd(data, occurred_dataset(scheduled), scheduled)
    data["pipeline"] = pipeline_snapshot(reader, now)
    write_exports(data, ROOT / "reports", f"{start}_{end}")
    print("Published V2 funnel and team CSVs from a shared V2 source cohort.")


if __name__ == "__main__":
    main()
